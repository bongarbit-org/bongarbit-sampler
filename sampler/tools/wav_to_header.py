#!/usr/bin/env python3
"""
wav_to_header.py - Convert a PCM WAV file into a C header with a flash-embeddable
int16_t array, for use with M16's Samp::setTable() (see sampler/src/main.cpp,
USE_SD_SAMPLER=0 path).

Supports mono/stereo, 8/16/24/32-bit integer PCM. Other bit depths are
downconverted to 16-bit with M16's own arithmetic, which at the pinned commit is
the same in Wav::load() (readAudioData), readFrames() and readFramesFast().

This used to promise that a sample "sounds identical whether played from SD or
from flash". The conversion is identical; the result is not. Wav::load() then
fades the first and last 10 ms of every buffer (applyEdgeFades()), and nothing
here does. The SD path matches this output only with WAV_RESTORE_EDGES=1 in
sampler/src/main.cpp, and only for a file loaded whole. See CLAUDE.md,
"Embedding a sample in flash".

Usage:
    python3 sampler/tools/wav_to_header.py <input.wav> <output.h> <ARRAY_NAME>

Example:
    python3 sampler/tools/wav_to_header.py sampler/samples/kick.wav sampler/src/kick_data.h KICK

Generates, in <output.h>:
    #define <ARRAY_NAME>_SAMPLE_RATE
    #define <ARRAY_NAME>_CHANNELS
    #define <ARRAY_NAME>_FRAME_COUNT
    const int16_t <ARRAY_NAME>_DATA[...] = { ... };
"""

import sys
import wave


def read_samples_16(path):
    w = wave.open(path, "rb")
    channels = w.getnchannels()
    sampwidth = w.getsampwidth()
    rate = w.getframerate()
    nframes = w.getnframes()
    raw = w.readframes(nframes)
    w.close()

    total_samples = nframes * channels
    samples16 = [0] * total_samples

    if sampwidth == 1:
        # WAV 8-bit PCM is unsigned, centered at 128.
        for i in range(total_samples):
            samples16[i] = (raw[i] - 128) << 8
    elif sampwidth == 2:
        for i in range(total_samples):
            off = i * 2
            val = raw[off] | (raw[off + 1] << 8)
            if val & 0x8000:
                val -= 0x10000
            samples16[i] = val
    elif sampwidth == 3:
        for i in range(total_samples):
            off = i * 3
            val = raw[off] | (raw[off + 1] << 8) | (raw[off + 2] << 16)
            if val & 0x800000:
                val -= 0x1000000
            samples16[i] = val >> 8
    elif sampwidth == 4:
        for i in range(total_samples):
            off = i * 4
            val = (
                raw[off]
                | (raw[off + 1] << 8)
                | (raw[off + 2] << 16)
                | (raw[off + 3] << 24)
            )
            if val & 0x80000000:
                val -= 0x100000000
            samples16[i] = val >> 16
    else:
        raise ValueError(f"Unsupported sample width: {sampwidth * 8}-bit")

    return channels, rate, nframes, samples16


def write_header(path, array_name, channels, rate, nframes, samples16):
    with open(path, "w") as f:
        f.write("#pragma once\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"// Auto-generated by sampler/tools/wav_to_header.py - do not edit by hand.\n")
        f.write(f"// Source: {channels}ch, {rate} Hz, {nframes} frames.\n\n")
        f.write(f"#define {array_name}_SAMPLE_RATE {rate}\n")
        f.write(f"#define {array_name}_CHANNELS {channels}\n")
        f.write(f"#define {array_name}_FRAME_COUNT {nframes}UL\n\n")
        f.write(f"const int16_t {array_name}_DATA[{len(samples16)}] = {{\n")
        line = []
        for s in samples16:
            line.append(str(s))
            if len(line) == 16:
                f.write(",".join(line) + ",\n")
                line = []
        if line:
            f.write(",".join(line) + "\n")
        f.write("};\n")


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        sys.exit(1)

    in_path, out_path, array_name = sys.argv[1], sys.argv[2], sys.argv[3]
    channels, rate, nframes, samples16 = read_samples_16(in_path)
    write_header(out_path, array_name, channels, rate, nframes, samples16)

    total_bytes = len(samples16) * 2
    print(f"{in_path}: {channels}ch, {rate} Hz, {nframes} frames "
          f"({nframes / rate:.2f}s)")
    print(f"Wrote {out_path}: {total_bytes} bytes "
          f"({array_name}_DATA, {array_name}_FRAME_COUNT, "
          f"{array_name}_SAMPLE_RATE, {array_name}_CHANNELS)")


if __name__ == "__main__":
    main()
